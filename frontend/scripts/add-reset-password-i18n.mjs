let updated = 0;
for (const [locale, keys] of Object.entries(T)) {
  const file = path.join(MESSAGES, `${locale}.json`);
  const json = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!json.Auth) {
    console.error(`SKIP ${locale}: no Auth namespace`);
    continue;
  }
  Object.assign(json.Auth, keys);
  fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n');
  updated++;
  console.log(`✓ ${locale}: +${Object.keys(keys).length} keys`);
}
console.log(`\nDone: ${updated}/17 locale files updated.`);
